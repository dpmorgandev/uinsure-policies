// Derives the kit's tokens from the chosen territory (design-system C1; guardrails A6): the palette from
// docs/ui/directions.json with the decided overrides, the families from the research's typography row,
// the scales from the stylesheet inputs. Writes src/web/kit/tokens/tokens.json (DTCG) and tokens.css,
// which follows the system theme and honours an explicit data-theme (THEME-1). Run by the main session
// at /stylesheet setup; the kit builder never edits either file.
//   node .claude/scripts/design/derive-tokens.mjs <territory> [--root <repo>]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const HARNESS = resolve(import.meta.dirname, '..', '..', '..');
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const HEX = /^#[0-9a-fA-F]{6}$/;

// "| T5 | Atkinson Hyperlegible Next + Atkinson Hyperlegible Mono | ..." → the two family names.
export function familiesFromRow(row) {
  const pair = row?.split('|')[2]?.trim() ?? '';
  const [sans, mono] = pair.split(' + ').map((s) => s.trim());
  if (!sans || !mono) throw new Error(`cannot read a sans + mono pair from: ${row}`);
  return { sans, mono };
}

export function deriveTokens(territory, families, spec) {
  const palette = structuredClone(territory?.derivedStyle?.palette ?? {});
  for (const [key, value] of Object.entries(spec.overrides ?? {})) {
    const [token, theme] = key.split('.');
    if (!palette[token] || !HEX.test(value)) throw new Error(`bad override ${key}=${value}`);
    palette[token][theme] = value;
  }
  const colors = Object.entries(palette);
  if (colors.length !== 10) throw new Error(`expected 10 colour tokens, found ${colors.length}`);
  const json = {
    color: Object.fromEntries(colors.map(([k, v]) => [k, {
      $type: 'color', $value: v.light, $extensions: { dark: v.dark, source: v.source, ...(v.graphicsOnly ? { graphicsOnly: true } : {}) },
    }])),
    font: {
      sans: { $type: 'fontFamily', $value: [families.sans, ...spec.fallback.sans] },
      mono: { $type: 'fontFamily', $value: [families.mono, ...spec.fallback.mono] },
    },
    size: Object.fromEntries(spec.typeScale.map((px) => [`text-${px}`, { $type: 'dimension', $value: `${px / 16}rem` }])),
    space: Object.fromEntries(spec.space.map((px, i) => [`space-${i + 1}`, { $type: 'dimension', $value: `${px / 16}rem` }])),
    radius: { $type: 'dimension', $value: `${spec.radius}px` },
    duration: Object.fromEntries(Object.entries(spec.duration).map(([k, ms]) => [k, { $type: 'duration', $value: `${ms}ms` }])),
  };
  const vars = (theme) => colors.map(([k, v]) => `  --color-${kebab(k)}: ${v[theme]};`).join('\n');
  const fonts = (f) => f.map((x) => (/\s/.test(x) && !x.includes('-') ? `"${x}"` : x)).join(', ');
  const css = `/* Generated by .claude/scripts/design/derive-tokens.mjs from docs/ui/directions.json. Do not edit. */
:root {
  --font-sans: ${fonts(json.font.sans.$value)};
  --font-mono: ${fonts(json.font.mono.$value)};
${spec.typeScale.map((px) => `  --text-${px}: ${px / 16}rem;`).join('\n')}
${spec.space.map((px, i) => `  --space-${i + 1}: ${px / 16}rem;`).join('\n')}
  --radius: ${spec.radius}px;
${Object.entries(spec.duration).map(([k, ms]) => `  --duration-${k}: ${ms}ms;`).join('\n')}
}
:root,
[data-theme="light"] {
${vars('light')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars('dark').replace(/^/gm, '  ')}
    color-scheme: dark;
  }
}
[data-theme="dark"] {
${vars('dark')}
  color-scheme: dark;
}
@media (prefers-reduced-motion: reduce) {
  :root {
${Object.keys(spec.duration).map((k) => `    --duration-${k}: 0ms;`).join('\n')}
  }
}
`;
  return { json, css };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const name = process.argv[2];
  const i = process.argv.indexOf('--root');
  const root = resolve(i > 0 ? process.argv[i + 1] : process.cwd());
  const spec = JSON.parse(readFileSync(join(HARNESS, '.claude', 'skills', 'stylesheet', 'inputs.json'), 'utf8')).tokens;
  const territory = JSON.parse(readFileSync(join(root, 'docs', 'ui', 'directions.json'), 'utf8')).territories.find((t) => t.name === name);
  if (!territory) throw new Error(`no territory ${name} in docs/ui/directions.json`);
  const id = territory.derivedStyle.type.sans;
  const row = readFileSync(join(root, 'docs', 'ui', 'research', 'mood-type-icons.md'), 'utf8').split('\n').find((l) => l.startsWith(`| ${id} |`));
  const { json, css } = deriveTokens(territory, familiesFromRow(row), spec);
  const dir = join(root, 'src', 'web', 'kit', 'tokens');
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
  writeFileSync(join(dir, 'tokens.css'), css);
  process.stdout.write(`tokens: ${Object.keys(json.color).length} colours, ${territory.derivedStyle.type.sans} type → src/web/kit/tokens/\n`);
}
