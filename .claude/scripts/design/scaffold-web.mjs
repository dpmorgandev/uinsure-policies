export function scaffold(root) {
  const written = [];
  for (const [rel, text] of Object.entries(FILES)) {
    const abs = join(root, rel);
    if (existsSync(abs)) continue;
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
    written.push(rel);
  }
  return written;
}

// The kit barrel (web-architecture C1, C2): one export line per component folder that has an index.ts,
// in catalog-tier order. Generated by the main session after the build waves, since parallel builders
// can't share one file. Overwrites: it is derived, never hand-edited.
export function barrel(root) {
  const kit = join(root, 'src', 'web', 'kit');
  const lines = ['// Generated by .claude/scripts/design/scaffold-web.mjs --barrel. Do not edit.'];
  for (const folder of ['primitives', 'patterns', 'layouts', 'project']) {
    const dir = join(kit, folder);
    if (!existsSync(dir)) continue;
    for (const id of readdirSync(dir).sort()) {
      if (existsSync(join(dir, id, 'index.ts'))) lines.push(`export * from './${folder}/${id}';`);
    }
  }
  writeFileSync(join(kit, 'index.ts'), lines.join('\n') + '\n');
  return lines.length - 1;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const i = process.argv.indexOf('--root');
  const root = resolve(i > 0 ? process.argv[i + 1] : process.cwd());
  if (process.argv.includes('--barrel')) {
    process.stdout.write(`barrel: ${barrel(root)} components → src/web/kit/index.ts\n`);
  } else {
    const written = scaffold(root);
    process.stdout.write(written.length ? `scaffolded: ${written.join(', ')}\n` : 'scaffold: nothing to write (all present)\n');
  }
}
